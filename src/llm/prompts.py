from typing import List, Dict, Any


# Системный промпт для RAG ассистента
SYSTEM_PROMPT = """Ты - профессиональный медицинский ассистент для работы с научными документами.

Твоя задача:
- Отвечать на вопросы пользователей на основе предоставленного контекста из документов
- Предоставлять точную и полную информацию
- Указывать источники информации (названия документов)
- Признаваться, если информации недостаточно для ответа

Правила:
1. Отвечай ТОЛЬКО на основе предоставленного контекста
2. Если в контексте нет ответа - так и скажи, не выдумывай
3. Структурируй ответ для лучшей читаемости
4. Используй профессиональную медицинскую терминологию
5. Указывай источники в конце ответа

Формат ответа:
[Основной ответ]

Источники:
- [Название документа 1]
- [Название документа 2]
"""


# Промпт для генерации ответа с контекстом
def create_synthesis_prompt(query: str, context_chunks: List[Dict[str, Any]]) -> str:
    """
    Создает промпт для генерации финального ответа.

    Args:
        query: Вопрос пользователя
        context_chunks: Список релевантных чанков с метаданными

    Returns:
        Отформатированный промпт
    """
    # Формируем контекст из чанков
    context_parts = []

    for idx, chunk in enumerate(context_chunks, 1):
        file_name = chunk.get("metadata", {}).get("file_name", "неизвестный документ")
        text = chunk.get("text", "")

        context_parts.append(f"[Документ {idx}: {file_name}]\n{text}")

    context = "\n\n".join(context_parts)

    # Создаем промпт
    prompt = f"""Контекст из медицинских документов:

{context}

---

Вопрос пользователя: {query}

Инструкция: На основе предоставленного контекста дай подробный и точный ответ на вопрос. Обязательно укажи источники информации в конце ответа."""

    return prompt


# Промпт для анализа запроса
