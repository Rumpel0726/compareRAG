# Промпт для академической оценки качества ответа (LLM-as-a-Judge)
ANSWER_EVALUATION_ACADEMIC_PROMPT = """Оцени качество ответа системы RAG на основе стандартизированных академических метрик.

Вопрос пользователя:
{query}

Найденный контекст (чанки, извлеченные ретривером):
{context}

Эталонный ответ (Ground Truth):
{reference_answer}

Сгенерированный ответ системы RAG:
{answer}

Оцени сгенерированный ответ по 4 критериям (по шкале от 1 до 5).
ВАЖНОЕ ПРАВИЛО: Оценивай смысл, а не дословное совпадение. При оценке учитывай специфику сложных предметных областей (медицинские термины, юридические формулировки, техническая документация). Не снижай баллы за бОльший объем текста, если он точен и уместен.

Критерии:
1. Answer Correctness (Точность ответа) — насколько факты в проверяемом ответе семантически совпадают с эталонным ответом. Строго проверяй логику, субъекты/объекты действия и числовые значения. 1 = искажен смысл, перепутаны роли или есть прямое противоречие эталону; 5 = смысловое ядро полностью совпадает, противоречий эталону нет.
2. Faithfulness (Обоснованность / Отсутствие галлюцинаций) — опирается ли сгенерированный ответ ИСКЛЮЧИТЕЛЬНО на предоставленный контекст. Модель не должна додумывать факты из своих базовых знаний. 1 = ответ содержит выдуманные факты, цифры или статьи закона, которых нет в предоставленном контексте (критичная галлюцинация); 5 = абсолютно каждое утверждение в ответе можно подтвердить текстом из контекста.
3. Answer Relevancy (Релевантность) — насколько прямо, полезно и без лишней "воды" сгенерированный ответ решает задачу, поставленную в вопросе. 1 = ответ уходит от темы или дает общую теорию вместо конкретики; 5 = ответ дает прямой и исчерпывающий ответ на суть вопроса.
4. Completeness (Полнота) — охватывает ли проверяемый ответ все ключевые аспекты эталона (например, необходимые SQL-запросы, исключения из юридических правил или медицинские показатели). 1 = упущена главная мысль или критически важная деталь; 5 = вся суть эталонного ответа сохранена.

Отвечай ТОЛЬКО валидным JSON без дополнительных комментариев:
{{
    "answer_correctness": оценка,
    "faithfulness": оценка,
    "answer_relevancy": оценка,
    "completeness": оценка,
    "reasoning": "Краткое обоснование. Обязательно укажи причину, если была обнаружена галлюцинация (снижен faithfulness) или фактологическая ошибка/подмена понятий (снижен correctness)."
}}
"""


def create_answer_evaluation_academic_prompt(
    query: str,
    answer: str,
    context: str,
    reference_answer: str,
) -> str:
    """
    Создает промпт для академической оценки качества ответа.

    Args:
        query: Вопрос
        answer: Проверяемый ответ системы RAG
        context: Контекст из базы знаний
        reference_answer: Эталонный ответ

    Returns:
        Отформатированный промпт
    """
    return ANSWER_EVALUATION_ACADEMIC_PROMPT.format(
        query=query,
        answer=answer,
        context=context,
        reference_answer=reference_answer,
    )
