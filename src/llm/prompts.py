# Промпт для оценки качества ответа (LLM-as-a-Judge)
ANSWER_EVALUATION_PROMPT = """Оцени качество ответа системы RAG.

Контекст (релевантные документы из базы знаний):
{context}

Вопрос пользователя:
{query}

Ответ системы:
{answer}

Оцени ответ по следующим 4 критериям (оценка от 1 до 5):
1. Correctness (Правильность) — насколько факты в ответе соответствуют предоставленному контексту. 1 = грубые фактические ошибки или галлюцинации, 5 = все факты точно подтверждены контекстом.
2. Relevance (Релевантность) — отвечает ли ответ на заданный вопрос. 1 = ответ не по теме, 5 = ответ полностью и точно адресует вопрос.
3. Completeness (Полнота) — охвачены ли все существенные аспекты вопроса на основании доступного контекста. 1 = ответ поверхностный, 5 = все доступные в контексте аспекты раскрыты.
4. Coherence (Согласованность) — логично и связно ли изложен ответ. 1 = текст бессвязен, 5 = изложение логично, структурировано и легко читается.

Отвечай ТОЛЬКО валидным JSON без дополнительных комментариев:
{{
    "correctness": оценка,
    "relevance": оценка,
    "completeness": оценка,
    "coherence": оценка,
    "reasoning": "краткое обоснование оценок"
}}
"""


def create_query_analysis_prompt(query: str) -> str:
    """
    Создает промпт для анализа запроса.

    Args:
        query: Запрос пользователя

    Returns:
        Отформатированный промпт
    """
    return QUERY_ANALYSIS_PROMPT.format(query=query)


def create_question_generation_prompt(document_text: str, num_questions: int = 5) -> str:
    """
    Создает промпт для генерации вопросов.

    Args:
        document_text: Текст документа
        num_questions: Количество вопросов

    Returns:
        Отформатированный промпт
    """
    # Ограничиваем длину текста для промпта
    max_length = 3000
    if len(document_text) > max_length:
        document_text = document_text[:max_length] + "..."

    return QUESTION_GENERATION_PROMPT.format(
        document_text=document_text,
        num_questions=num_questions
    )


def create_answer_evaluation_prompt(
    query: str,
    answer: str,
    context: str
) -> str:
    """
    Создает промпт для оценки качества ответа.

    Args:
        query: Вопрос
        answer: Ответ системы
        context: Контекст из документов

    Returns:
        Отформатированный промпт
    """
    return ANSWER_EVALUATION_PROMPT.format(
        query=query,
        answer=answer,
        context=context
    )


